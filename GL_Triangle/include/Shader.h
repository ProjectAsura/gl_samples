#pragma once

//-----------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------
#include <cstdint>


///////////////////////////////////////////////////////////////////////////////
// Shader class
///////////////////////////////////////////////////////////////////////////////
class Shader
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    enum Kind
    {
        VS,     //!< 頂点シェーダ.
        PS,     //!< ピクセルシェーダ.
        GS,     //!< ジオメトリシェーダ.
        DS,     //!< ドメインシェーダ.
        HS,     //!< ハルシェーダ.
        CS,     //!< コンピュートシェーダ.
    };

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Shader();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Shader();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      kind        シェーダ種別.
    //! @param[in]      pBinary     バイナリデータ.
    //! @param[in]      binarySize  バイナリサイズ.
    //! @param[in]      entryPoint  メインエントリーポイント名.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(Kind kind, const void* pBinary, uint32_t binarySize, const char* entryPoint = "main");

    //-------------------------------------------------------------------------
    //! @brief      ファイルから初期化処理を行います.
    //! 
    //! @param[in]      kind        シェーダ種別.
    //! @param[in]      filename    ファイル名.
    //! @param[in]      entryPoint  メインエントリーポイント名.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool InitFromFile(Kind kind, const char* filename, const char* entryPoint = "main");

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      シェーダを取得します.
    //! 
    //! @return     シェーダを返却します.
    //-------------------------------------------------------------------------
    uint32_t Get() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    uint32_t m_Shader = 0;    //!< シェーダ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

///////////////////////////////////////////////////////////////////////////////
// ShaderProgram class
///////////////////////////////////////////////////////////////////////////////
class ShaderProgram
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    ShaderProgram();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~ShaderProgram();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const Shader** shaders, size_t shaderCount);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      シェーダプログラムをバインドします.
    //-------------------------------------------------------------------------
    void Bind();

    //-------------------------------------------------------------------------
    //! @brief      シェーダプログラムのバインドを解除します.
    //-------------------------------------------------------------------------
    void Unbind();

    //-------------------------------------------------------------------------
    //! @brief      シェーダプログラムを取得します.
    //! 
    //! @return     シェーダプログラムを返却します.
    //-------------------------------------------------------------------------
    uint32_t Get() const;

    //-------------------------------------------------------------------------
    //! @brief      頂点属性ロケーションを取得します.
    //! 
    //! @param[in]      name        頂点属性名.
    //! @return     頂点属性ロケーションを返却します.
    //! @note       無効な頂点属性ロケーションの場合は -1 が返却されます.
    //-------------------------------------------------------------------------
    int GetAttribute(const char* name) const;

    //-------------------------------------------------------------------------
    //! @brief      ユニフォームロケーションを取得します.
    //! 
    //! @param[in]      name        頂点属性名.
    //! @return     ユニフォームロケーションを返却します.
    //! @note       無効なユニフォームロケーションの場合は -1 が返却されます.
    //-------------------------------------------------------------------------
    int GetUniform(const char* name) const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    uint32_t m_Program = 0;   //!< シェーダプログラム.

    //=========================================================================
    // private methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      シェーダプログラムをリンクします.
    //! 
    //! @retval true    リンクに成功.
    //! @retval false   リンクに失敗.
    //-------------------------------------------------------------------------
    bool Link();
};