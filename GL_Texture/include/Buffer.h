///////////////////////////////////////////////////////////////////////////////
// Attribute structure
///////////////////////////////////////////////////////////////////////////////
struct Attribute
{
    int         Location;       //!< ロケーション番号.
    int         Count;          //!< 要素数.
    uint32_t    DataType;       //!< 要素のデータ型.
    uint8_t     Normalized;     //!< 正規化する場合は 1.
    ptrdiff_t   Offset;         //!< 先頭からのデータオフセット.
};

///////////////////////////////////////////////////////////////////////////////
// InputLayout structure
///////////////////////////////////////////////////////////////////////////////
struct InputLayout
{
    const Attribute*    pAttributes     = nullptr;
    uint32_t            AttributeCount  = 0;
};


///////////////////////////////////////////////////////////////////////////////
// VertexBuffer class
///////////////////////////////////////////////////////////////////////////////
class VertexBuffer
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    VertexBuffer();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~VertexBuffer();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      vertices        頂点データです.
    //! @param[in]      vertexCount     頂点数.
    //! @param[in]      vertexStride    1頂点あたりのデータサイズ.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const void* vertices, uint32_t vertexCount, uint32_t vertexStride);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      バッファオブジェクトを取得します.
    //! 
    //! @return     バッファをオブジェクトを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetHandle() const;

    //-------------------------------------------------------------------------
    //! @brief      頂点数を取得します.
    //! 
    //! @return     頂点数を返却します.
    //-------------------------------------------------------------------------
    uint32_t GetVertexCount() const;

    //-------------------------------------------------------------------------
    //! @brief      1頂点あたりのデータサイズを取得します.
    //! 
    //! @return     1頂点あたりのデータサイズを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetVertexStride() const;

    //-------------------------------------------------------------------------
    //! @brief      バッファオブジェクトをバインドします.
    //! 
    //! @param[in]      inputLayout     入力レイアウト.
    //-------------------------------------------------------------------------
    void Bind(const InputLayout& inputLayout);

    //-------------------------------------------------------------------------
    //! @brief      バッファオブジェクトのバインドを解除します.
    //! 
    //! @param[in]      inputLayout     入力レイアウト.
    //-------------------------------------------------------------------------
    void Unbind(const InputLayout& inputLayout);

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    uint32_t m_Handle       = 0;  //!< バッファオブジェクト.
    uint32_t m_VertexCount  = 0;  //!< 頂点数.
    uint32_t m_VertexStride = 0;  //!< 1頂点あたりのデータサイズ.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};


