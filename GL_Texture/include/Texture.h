#include <cstdint>


///////////////////////////////////////////////////////////////////////////////
// Textuer class
///////////////////////////////////////////////////////////////////////////////
class Texture
{
    //=========================================================================
    // list of friend classes and methods.
    //=========================================================================
    /* NOTHING */

public:
    ///////////////////////////////////////////////////////////////////////////
    // Desc structure
    ///////////////////////////////////////////////////////////////////////////
    struct Desc
    {
        int         Width;              //!< 横幅.
        int         Height;             //!< 縦幅.
        uint32_t    InternalFormat;     //!< 内部フォーマット.
        uint32_t    Format;             //!< ピクセルフォーマット.
        uint32_t    Type;               //!< ピクセルデータタイプ.
    };

    //=========================================================================
    // public variables.
    //=========================================================================
    /* NOTHING */

    //=========================================================================
    // public methods.
    //=========================================================================

    //-------------------------------------------------------------------------
    //! @brief      コンストラクタです.
    //-------------------------------------------------------------------------
    Texture();

    //-------------------------------------------------------------------------
    //! @brief      デストラクタです.
    //-------------------------------------------------------------------------
    ~Texture();

    //-------------------------------------------------------------------------
    //! @brief      初期化処理を行います.
    //! 
    //! @param[in]      desc        構成設定.
    //! @param[in]      ppPixels    ピクセルデータ.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool Init(const Desc& desc, const void* pPixels);

    //-------------------------------------------------------------------------
    //! @brief      ファイルから初期化を行います.
    //! 
    //! @param[in]      path        ファイルパスです.
    //! @retval true    初期化に成功.
    //! @retval false   初期化に失敗.
    //-------------------------------------------------------------------------
    bool InitFromFile(const char* path);

    //-------------------------------------------------------------------------
    //! @brief      終了処理を行います.
    //-------------------------------------------------------------------------
    void Term();

    //-------------------------------------------------------------------------
    //! @brief      バインドします.
    //! 
    //! @param[in]      binding     バインディング番号.
    //-------------------------------------------------------------------------
    void Bind(int binding);

    //-------------------------------------------------------------------------
    //! @brief      バインドを解除します.
    //! 
    //! @param[in]      binding     バインディング番号.
    //-------------------------------------------------------------------------
    void Unbind(int binding);

    //-------------------------------------------------------------------------
    //! @brief      テクスチャオブジェクトを取得します.
    //! 
    //! @return     テクスチャオブジェクトを返却します.
    //-------------------------------------------------------------------------
    uint32_t GetHandle() const;

    //-------------------------------------------------------------------------
    //! @brief      構成設定を取得します.
    //! 
    //! @return     構成設定を返却します.
    //-------------------------------------------------------------------------
    const Desc& GetDesc() const;

private:
    //=========================================================================
    // private variables.
    //=========================================================================
    uint32_t    m_Handle = 0;       //!< テクスチャオブジェクト.
    Desc        m_Desc   = {};      //!< 構成設定.

    //=========================================================================
    // private methods.
    //=========================================================================
    /* NOTHING */
};

